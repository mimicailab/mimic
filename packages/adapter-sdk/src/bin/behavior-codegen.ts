#!/usr/bin/env node
/**
 * Shared behavior pack codegen — usable by any adapter.
 *
 * Reads every `<cwd>/src/behavior/*.yaml` pack and emits
 * `<cwd>/src/generated/behavior.ts` exporting the parsed packs as a typed
 * array. Mirrors the OpenAPI codegen pattern: YAML is the human-authored
 * source of truth; the runtime imports compiled data (no YAML at runtime).
 *
 * Run from an adapter package root:
 *   mimic-behavior-codegen
 *   (or: npx tsx node_modules/@mimicai/adapter-sdk/dist/bin/behavior-codegen.js)
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { loadBehaviorPack } from '../behavior/loader.js';

function main(): void {
  const cwd = process.cwd();
  const behaviorDir = resolve(cwd, 'src/behavior');
  const outFile = resolve(cwd, 'src/generated/behavior.ts');

  if (!existsSync(behaviorDir)) {
    console.log('No src/behavior/ directory; nothing to generate.');
    return;
  }

  const files = readdirSync(behaviorDir)
    .filter((f) => f.endsWith('.yaml') || f.endsWith('.yml'))
    .sort();

  if (files.length === 0) {
    console.log('No behavior packs found in src/behavior/.');
    return;
  }

  const packs = files.map((f) => loadBehaviorPack(readFileSync(resolve(behaviorDir, f), 'utf-8')));
  const totalActions = packs.reduce((n, p) => n + p.actions.length, 0);

  const out = `// AUTO-GENERATED by @mimicai/adapter-sdk behavior codegen — do not edit.
// Source: src/behavior/*.yaml  (${files.length} pack(s): ${files.map((f) => basename(f)).join(', ')}; ${totalActions} action(s))
import type { BehaviorPack } from '@mimicai/adapter-sdk';

/** Compiled behavior packs, one per src/behavior/*.yaml file. */
export const behaviorPacks: BehaviorPack[] = ${JSON.stringify(packs, null, 2)} as unknown as BehaviorPack[];
`;

  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, out);
  console.log(`Generated ${outFile} from ${files.join(', ')} (${totalActions} actions).`);
}

main();
